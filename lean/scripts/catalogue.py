#!/usr/bin/env python3
"""Writes the catalogue of the formalised results into README.md, and Axioms.lean, from results.tsv.

results.tsv has one row per numbered result of the thesis that is formalised here: the thesis's main
results, and the results they rest on. Each row gives the number, kind, title, status, the Lean
names that prove or formalise it, their files, the results its proof cites in the thesis, and its
role (main or supporting). The script rewrites the part of README.md between the results markers:
a table of the main results and a table of the supporting ones. It also writes
Axioms.lean, which prints the axioms of every Lean name in results.tsv, and of the cited results
proved here.

Usage, from lean/: python3 scripts/catalogue.py [--check]
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
START, END = '<!-- results:start -->', '<!-- results:end -->'
STYLE = {'Proved': 'done', 'Formalised': 'done'}  # the statuses allowed in results.tsv
ROLES = ('main', 'supporting')


def key(n):
    return [int(p) for p in n.split('.')]


def rows():
    out = []
    for line in (HERE / 'results.tsv').read_text(encoding='utf-8').splitlines():
        if not line or line.startswith('#'):
            continue
        number, kind, title, status, lean, files, uses, role = (line.split('\t') + [''] * 8)[:8]
        if status not in STYLE:
            sys.exit(f'catalogue: unknown status {status!r} for {number}')
        if role not in ROLES:
            sys.exit(f'catalogue: unknown role {role!r} for {number}')
        out.append(dict(number=number, kind=kind, title=title, status=status,
                        lean=lean.split(), files=files.split(),
                        uses=sorted(uses.split(), key=key), role=role))
    return out


def render(rs):
    lines = [START]

    def table(role):
        out = ['| Result | Lean |', '| --- | --- |']
        for r in (r for r in rs if r['role'] == role):
            title = f"{r['kind']} {r['number']}" + (f" ({r['title']})" if r['title'] else '')
            files = ', '.join(f'`{f}.lean`' for f in r['files'])
            names = ', '.join(f'`{x}`' for x in r['lean'])
            out.append(f"| {title} | {names} ({files}) |")
        return out

    lines += ['', '### Main results', ''] + table('main')
    lines += ['', '### Supporting results', '',
              'The numbered results of the thesis that the main results rest on.', ''] + table('supporting')
    lines += ['', END]
    return '\n'.join(lines)


# Classical results the thesis cites, proved here though not numbered in the thesis.
EXTRA = ['peano_exists', 'maxSol_isMaximal']

AXIOMS_HEAD = '''/-
Copyright (c) 2026 Ryan McCrickerd. All rights reserved.
Released under Apache 2.0 license as described in the file LICENSE.
Authors: Ryan McCrickerd
-/
import PathwiseVolatility

/-! Prints the axioms of every result in the catalogue: `lake env lean Axioms.lean`. Each should
list only `propext`, `Classical.choice` and `Quot.sound`. Generated by `scripts/catalogue.py` from
`results.tsv`. -/

'''


def axioms(rs):
    names = []
    for n in [x for r in rs for x in r['lean']] + EXTRA:
        if n not in names:
            names.append(n)
    return AXIOMS_HEAD + ''.join(f'#print axioms PathwiseVolatility.{n}\n' for n in names)


def main():
    readme = HERE / 'README.md'
    text = readme.read_text(encoding='utf-8')
    if START not in text or END not in text:
        sys.exit('catalogue: README.md has no results markers')
    new = text[:text.index(START)] + render(rows()) + text[text.index(END) + len(END):]
    ax_path = HERE / 'Axioms.lean'
    ax = axioms(rows())
    if '--check' in sys.argv:
        ok = new == text and ax_path.read_text(encoding='utf-8') == ax
        sys.exit(0 if ok else 'catalogue: README.md or Axioms.lean is out of date; run scripts/catalogue.py')
    readme.write_text(new, encoding='utf-8')
    ax_path.write_text(ax, encoding='utf-8')


if __name__ == '__main__':
    main()
